"""Browser checks against seeded disposable localhost deployment, never Render."""
import os
from urllib.parse import urlparse
from playwright.sync_api import sync_playwright, expect

def run():
    url=os.environ['TEST_BROWSER_URL'].rstrip('/')
    assert urlparse(url).hostname in ('localhost','127.0.0.1') and urlparse(url).port!=8000
    errors=[]
    with sync_playwright() as p:
        browser=p.chromium.launch(headless=True,executable_path=os.environ['TEST_BROWSER_EXECUTABLE'])
        page=browser.new_page(viewport={'width':1366,'height':1000})
        page.add_init_script("sessionStorage.setItem('ottv2_session','rank-token-25')")
        page.on('pageerror',lambda e:errors.append(str(e)))
        page.goto(url);page.locator('#modeDaily').click()
        expect(page.locator('#dailyLeaderboard tr')).to_have_count(10)
        expect(page.locator('#dailyStandingMe')).to_contain_text('hạng 26')
        expect(page.locator('#dailyStandingInfo')).to_contain_text('1–10 trên 26')
        expect(page.locator('#dailyStandingPrev')).to_be_disabled()
        page.locator('#dailyStandingNext').click()
        expect(page.locator('#dailyLeaderboard tr').first.locator('td').first).to_have_text('11')
        page.locator('#dailyStandingNext').click()
        expect(page.locator('#dailyLeaderboard tr')).to_have_count(6)
        expect(page.locator('#dailyStandingNext')).to_be_disabled()
        expect(page.locator('#dailyLeaderboard .daily-standing-own')).to_have_count(1)
        page.locator('#dailyStandingPrev').click()
        expect(page.locator('#dailyLeaderboard tr').first.locator('td').first).to_have_text('11')
        page.locator('#dailyStandingLocate').click()
        expect(page.locator('#dailyStandingInfo')).to_contain_text('21–26 trên 26')
        page.locator('#dailyDay').fill('2026-10-25')
        expect(page.locator('#dailyStandingInfo')).to_contain_text('1–10 trên 12')
        expect(page.locator('#dailyStandingLocate')).not_to_be_visible()
        expect(page.locator('#dailyStandingMe')).to_contain_text('chưa có kết quả')
        page.locator('#dailyDay').fill('2000-01-01')
        expect(page.locator('#dailyStandingInfo')).to_contain_text('0 trên 0')
        expect(page.locator('#dailyStandingNext')).to_be_disabled()
        page.locator('#dailyDay').fill('')
        expect(page.locator('#dailyStandingInfo')).to_contain_text('1–10 trên 26')
        page.locator('[data-open-leaderboard]').click()
        page.locator('#leaderboardMode').select_option('daily')
        expect(page.locator('#leaderboardBody tr')).to_have_count(10)
        expect(page.locator('#modalStandingMe')).to_contain_text('hạng 26')
        page.locator('#modalStandingLocate').click()
        expect(page.locator('#modalStandingInfo')).to_contain_text('21–26 trên 26')
        expect(page.locator('#leaderboardBody .daily-standing-own')).to_have_count(1)
        page.locator('#leaderboardDailyDay').fill('2026-10-25')
        expect(page.locator('#modalStandingInfo')).to_contain_text('1–10 trên 12')
        expect(page.locator('#leaderboardPeriod')).to_contain_text('25/10/2026')
        page.locator('#leaderboardMode').select_option('tournament')
        expect(page.locator('#leaderboardDailyPages')).not_to_be_visible()
        expect(page.locator('#leaderboardDailySelf')).not_to_be_visible()
        expect(page.locator('#leaderboardTournamentFilter')).to_be_visible()
        page.locator('#leaderboardMode').select_option('daily')
        expect(page.locator('#modalStandingInfo')).to_contain_text('1–10 trên 12')
        page.locator('#leaderboardDailyDay').fill('')
        expect(page.locator('#modalStandingInfo')).to_contain_text('1–10 trên 26')
        page.route('**/api/daily/leaderboard?*',lambda r:r.fulfill(status=503,content_type='application/json',body='{"detail":"Test temporary error"}'))
        page.locator('#modalStandingNext').click()
        expect(page.locator('#modalStandingInfo')).to_contain_text('Test temporary error')
        expect(page.locator('#modalStandingNext')).to_be_disabled()
        page.unroute('**/api/daily/leaderboard?*')
        page.locator('#closeLeaderboard').click();page.locator('[data-open-leaderboard]').click()
        expect(page.locator('#modalStandingInfo')).to_contain_text('11–20 trên 26')
        page.set_viewport_size({'width':390,'height':844})
        assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'Mobile page overflow'
        assert page.locator('#leaderboardDialog').evaluate('(e)=>e.getBoundingClientRect().width<=innerWidth'),'Dialog overflow'
        if os.getenv('TEST_SCREENSHOT'):page.locator('#leaderboardDialog').screenshot(path=os.environ['TEST_SCREENSHOT'],animations='disabled')
        page.locator('#closeLeaderboard').click()
        page.locator('#navAccount').click();page.locator('#logoutBtn').click()
        expect(page.locator('#dailyStandingMe')).to_contain_text('Đăng nhập')
        expect(page.locator('#dailyLeaderboard .daily-standing-own')).to_have_count(0)
        expect(page.locator('#dailyStandingLocate')).not_to_be_visible()
        assert not errors,errors
        browser.close()
    print('PASS: 26 teams; both pagers; global ranks; own-rank jump/highlight; date/empty filters; Tournament switch; error recovery; logout; mobile layout')
if __name__=='__main__':run()
